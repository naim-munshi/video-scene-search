"""Generate a rights-cleared *synthetic* multimodal demo and its exact labels.

Do not present its evaluation as real-world retrieval accuracy. Generated video
is kept under data/ (ignored by git) and does not require external downloads.

Usage:
    python scripts/synthetic_demo.py generate
    scene-search ingest --manifest data/demo-corpus.json --output artifacts/demo-index --whisper-model tiny --language en
    python scripts/synthetic_demo.py labels --index artifacts/demo-index
    scene-search evaluate --index artifacts/demo-index --labels evaluation/demo-labels.json --split test --output reports/demo-test
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

# Each row maps to exactly one 10s time window. The words are chosen as
# distinctive, audible cues; no people or actual events are depicted.
SCENES = (
    (("red", "The red screen introduces our science experiment."),
     ("blue", "The blue screen explains the project deadline."),
     ("green", "The green screen presents our financial budget.")),
    (("yellow", "The yellow screen describes a cooking recipe."),
     ("purple", "The purple screen discusses the train journey."),
     ("orange", "The orange screen announces the music concert.")),
    (("black", "The black screen summarizes the security review."),
     ("white", "The white screen explains the math homework."),
     ("pink", "The pink screen mentions the animal shelter.")),
)
TOPICS = (
    ("science experiment", "project deadline", "financial budget"),
    ("cooking recipe", "train journey", "music concert"),
    ("security review", "math homework", "animal shelter"),
)
# Query templates intentionally vary phrasing. A label only asserts that the
# specified colored card/topic occurs in the generated ground-truth window.
QUERY_TEMPLATES = (
    "The {color} screen", "A {color} scene while a narrator discusses {topic}", "A voice talks about {topic}"
)


def _require_ffmpeg():
    ffmpeg = shutil.which("ffmpeg")
    if ffmpeg is None:
        raise RuntimeError("ffmpeg is required (on macOS: brew install ffmpeg)")
    proc = subprocess.run([ffmpeg, "-hide_banner", "-filters"],
                          text=True, capture_output=True, check=True)
    if not re.search(r"\bflite\b", proc.stdout):
        raise RuntimeError("This ffmpeg lacks the flite text-to-speech filter. "
                           "Use a build with libflite, or bring your own licensed videos.")
    return ffmpeg


def generate(root):
    ffmpeg = _require_ffmpeg()
    root = Path(root).resolve()
    if (root / "demo-corpus.json").exists():
        raise ValueError("Demo already exists; use a fresh --root (no overwrites)")
    videos_dir = root / "videos" / "demo"
    videos_dir.mkdir(parents=True, exist_ok=True)
    entries = []
    for idx, scenes in enumerate(SCENES, start=1):
        vid = f"demo_{idx:02d}"
        path = videos_dir / (vid + ".mp4")
        cmd = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y"]
        for color, sentence in scenes:
            # All source text is controlled by constants in this script.
            cmd += ["-f", "lavfi", "-i", f"color=c={color}:s=320x240:r=5:d=10",
                    "-f", "lavfi", "-i", f"flite=text='{sentence}':voice=slt"]
        filters = []
        for i in range(len(scenes)):
            filters.append(f"[{i*2+1}:a]apad,atrim=duration=10,asetpts=PTS-STARTPTS[a{i}]")
        inputs = "".join(f"[{2*i}:v][a{i}]" for i in range(len(scenes)))
        filters.append(f"{inputs}concat=n={len(scenes)}:v=1:a=1[v][a]")
        cmd += ["-filter_complex", ";".join(filters), "-map", "[v]", "-map", "[a]",
                "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
                "-c:a", "aac", "-movflags", "+faststart", str(path)]
        subprocess.run(cmd, check=True)
        entries.append({"id": vid, "title": f"Synthetic demo {idx}: three colored cards with speech",
                        "path": f"videos/demo/{vid}.mp4", "source": "Generated by scripts/synthetic_demo.py",
                        "license": "Generated locally for software testing; not third-party footage",
                        "attribution": "FFmpeg lavfi and flite synthetic fixture",
                        "rights_confirmed": True})
    from scene_search.core import write_json
    manifest = root / "demo-corpus.json"
    write_json(manifest, {"corpus_kind": "synthetic_fixture", "videos": entries})
    return manifest


def create_labels(index, output):
    from scene_search.core import read_json, sha256, write_json
    index = Path(index).resolve()
    output = Path(output).resolve()
    if output.exists():
        raise ValueError("Labels already exist; choose a fresh output")
    windows = read_json(index / "windows.json")
    expected = {f"demo_{i:02d}:{j:05d}" for i in range(1, 4) for j in range(3)}
    actual = {w["id"] for w in windows}
    if actual != expected or any(abs(w["end"] - w["start"] - 10) > 0.3 for w in windows):
        raise ValueError("This index is not the expected three-clip synthetic demo; "
                         "do not apply synthetic ground truth to other videos")
    queries = []
    for i, scenes in enumerate(SCENES, start=1):
        for j, (color, _) in enumerate(scenes):
            for kind_idx, pattern in enumerate(QUERY_TEMPLATES):
                # Three queries per scene, omit the final three to make 24 total.
                if len(queries) == 24:
                    break
                qid = f"demo-q{len(queries)+1:02d}"
                queries.append({"id": qid, "text": pattern.format(color=color, topic=TOPICS[i-1][j]),
                                "kind": ("visual", "mixed", "speech")[kind_idx],
                                "split": "dev" if len(queries) < 6 else "test",
                                "relevant": [f"demo_{i:02d}:{j:05d}"]})
    write_json(output, {"status": "annotated", "label_provenance": "synthetic_deterministic_not_manual",
                        "build_sha256": sha256(index / "build.json"), "queries": queries})
    return output


def main():
    p = argparse.ArgumentParser(description=__doc__)
    s = p.add_subparsers(dest="command", required=True)
    a = s.add_parser("generate", help="Create 3 short videos with synthesized audio")
    a.add_argument("--root", default="data")
    b = s.add_parser("labels", help="Produce deterministic labels only for this demo index")
    b.add_argument("--index", default="artifacts/demo-index")
    b.add_argument("--output", default="evaluation/demo-labels.json")
    args = p.parse_args()
    try:
        if args.command == "generate":
            result = {"manifest": str(generate(args.root)), "note": "Synthetic media only. Not real-world quality evidence."}
        else:
            result = {"labels": str(create_labels(args.index, args.output)),
                      "note": "Synthetic ground truth only. Do not publish as real-data Recall@5."}
    except (ValueError, OSError, subprocess.CalledProcessError, RuntimeError) as exc:
        p.exit(2, f"Error: {exc}\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    # Running from the repository root without installing is supported.
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
    main()
