import os
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from scene_search.core import read_json, sha256, write_json


class FixtureEncoder:
    def __init__(self, *args, **kwargs):
        pass

    def encode(self, values, **kwargs):
        import numpy as np
        rows = []
        for value in values:
            if isinstance(value, str):
                rows.append([1, 0] if "red" in value.lower() else [0, 1])
            else:
                pixel = np.asarray(value).mean(axis=(0, 1))
                rows.append([1, 0] if pixel[0] > pixel[2] else [0, 1])
        return np.array(rows, dtype="float32")


class FixtureWhisper:
    def __init__(self, *args, **kwargs):
        pass

    def transcribe(self, *args, **kwargs):
        return iter([SimpleNamespace(start=0, end=2, text="red screen"),
                     SimpleNamespace(start=2, end=4, text="blue screen")]), SimpleNamespace(language="en")


@unittest.skipUnless(os.environ.get("RUN_INTEGRATION") == "1", "Set RUN_INTEGRATION=1; requires ML dependencies")
class IntegrationTests(unittest.TestCase):
    def setUp(self):
        import av
        import numpy as np
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        video = self.root / "fixture.mp4"
        with av.open(str(video), mode="w") as container:
            stream = container.add_stream("mpeg4", rate=2)
            stream.width = 64
            stream.height = 64
            stream.pix_fmt = "yuv420p"
            for i in range(8):
                picture = np.zeros((64, 64, 3), dtype="uint8")
                picture[:, :, 0 if i < 4 else 2] = 255  # RGB red, then blue
                frame = av.VideoFrame.from_ndarray(picture, format="rgb24")
                for packet in stream.encode(frame):
                    container.mux(packet)
            for packet in stream.encode():
                container.mux(packet)
        write_json(self.root / "corpus.json", {"videos": [{"id": "fixture", "path": "fixture.mp4",
            "title": "Synthetic software fixture", "source": "Generated by test",
            "license": "Test-only self-created", "attribution": "Integration test",
            "rights_confirmed": True}]})
        self.encoder_patch = patch("sentence_transformers.SentenceTransformer", FixtureEncoder)
        self.whisper_patch = patch("faster_whisper.WhisperModel", FixtureWhisper)
        self.encoder_patch.start()
        self.whisper_patch.start()
        self.addCleanup(self.encoder_patch.stop)
        self.addCleanup(self.whisper_patch.stop)
        from scene_search.pipeline import build
        self.output = self.root / "index"
        result = build(self.root / "corpus.json", self.output, frame_seconds=1,
                       window_seconds=2, embedding_mode="in-process")
        self.assertEqual(result["frames"], 4)
        self.assertEqual(result["windows"], 2)

    def test_ingest_restart_search_evaluate(self):
        from scene_search.search import SearchEngine
        from scene_search.evaluate import evaluate
        engine = SearchEngine(self.output, device="cpu", embedding_mode="in-process")
        for mode in ("visual", "transcript", "hybrid"):
            self.assertEqual(engine.search("red screen", mode)[0]["id"], "fixture:00000")
            self.assertEqual(engine.search("blue screen", mode)[0]["start"], 2)
        # Reload native indexes from disk, not the build's in-memory objects.
        self.assertEqual(SearchEngine(self.output, device="cpu", embedding_mode="in-process").search("red")[0]["id"], "fixture:00000")
        write_json(self.root / "labels.json", {"status": "annotated",
            "build_sha256": sha256(self.output / "build.json"), "queries": [
                {"id": "fixture-q1", "text": "red", "kind": "visual", "split": "test",
                 "relevant": ["fixture:00000"]}]})
        rows = evaluate(engine, self.root / "labels.json", self.root / "report")
        self.assertEqual(len([r for r in rows if r["kind"] == "all"]), 3)

    def test_corrupt_index_rejected_before_native_load(self):
        from scene_search.search import SearchEngine
        (self.output / "visual.faiss").write_bytes(b"corrupt")
        with self.assertRaisesRegex(ValueError, "integrity"):
            SearchEngine(self.output, device="cpu", embedding_mode="in-process")

    def test_ui_search_and_annotation(self):
        from streamlit.testing.v1 import AppTest
        with patch.dict(os.environ, {"SCENE_INDEX": str(self.output),
                                  "SCENE_EMBEDDING_MODE": "in-process"}):
            app = AppTest.from_file(str(Path(__file__).parents[1] / "app.py")).run(timeout=30)
            self.assertFalse(app.exception)
            app.text_input[0].set_value("red screen")
            app.button[0].click().run(timeout=30)
            self.assertFalse(app.exception)
            self.assertEqual(len(app.dataframe), 1)
            self.assertEqual(app.session_state["results"][0]["id"], "fixture:00000")
            self.assertTrue(app.get("video"))
            app.text_input[2].set_value("Find the red screen")
            app.multiselect[0].set_value(["fixture:00000"])
            app.button[1].click().run(timeout=30)
            self.assertFalse(app.exception)
            self.assertEqual(len(app.session_state["annotations"]["queries"]), 1)
